"""One-edge-at-a-time growth of a typed phrase graph.

Unlike a post-hoc repair, this lane admits an edge only when both independently
written clause options satisfy the live character frontier.  The graph grows
from the 156-letter incumbent and keeps the new edge provenance explicit.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from experiments.typed_phrase_graph_palindromes_20260928 import (
    LEFT,
    RIGHT,
    Phrase,
    exact_two_pointer,
    letters,
    validator,
)


# These are ordinary scene clauses authored as typed SVO/vocative options.
# They are not generated by reversing the incumbent tape.  The matching mate
# is a separate clause option and is checked before an edge is admitted.
GROWTH_EDGES = (
    (
        Phrase("Nora, I saw deliver.", "vocative-perception-growth"),
        Phrase("Reviled was I, Aron.", "copular-return-growth"),
    ),
    (
        Phrase("Noel, I saw diaper.", "vocative-perception-growth"),
        Phrase("Repaid was I, Leon.", "copular-return-growth"),
    ),
)


def exact_edge(left: Phrase, right: Phrase) -> bool:
    return left.tape == right.tape[::-1]


def grow_edges() -> tuple[list[tuple[Phrase, Phrase]], list[dict]]:
    accepted = [(Phrase(x.text, x.kind), Phrase(y.text, y.kind)) for x, y in zip(LEFT, RIGHT)]
    trace = [{"edge": "incumbent", "accepted": True, "reason": "seed lineage"}]
    used = {p.tape for edge in accepted for p in edge}
    for left, right in GROWTH_EDGES:
        duplicate = left.tape in used or right.tape in used
        matched = exact_edge(left, right)
        accepted_edge = matched and not duplicate
        trace.append({
            "left": left.text,
            "right": right.text,
            "matched_online": matched,
            "duplicate_unit": duplicate,
            "accepted": accepted_edge,
        })
        if accepted_edge:
            accepted.append((left, right))
            used.update((left.tape, right.tape))
    return accepted, trace


def audit(candidate: str, edges: list[tuple[Phrase, Phrase]], trace: list[dict]) -> dict:
    tape = letters(candidate)
    units = [unit.tape for edge in edges for unit in edge]
    return {
        "text": candidate,
        "letters": len(tape),
        "normalized": tape,
        "exact_two_pointer": exact_two_pointer(candidate),
        "validator": validator(candidate),
        "sha256": hashlib.sha256(tape.encode()).hexdigest(),
        "independent_forward_reverse_sha256": hashlib.sha256(tape[::-1].encode()).hexdigest(),
        "novelty_preflight": len(units) == len(set(units)),
        "provenance": {
            "base": "typed-phrase-graph-palindromes-20260928.json",
            "growth_operator": "online typed edge admission with distinct clause tapes",
            "growth_edges": [item for item in trace if item.get("edge") != "incumbent"],
            "distinct_units": len(units) == len(set(units)),
            "self_palindromic_units": any(unit == unit[::-1] for unit in units),
            "catalogue_text": False,
            "posthoc_character_repair": False,
        },
        "reader_gate": "pending-blinded-human-ratings; formulaic seam debt disclosed",
    }


def run() -> dict:
    edges, trace = grow_edges()
    candidate = " ".join(
        [left.text for left, _ in edges] + [right.text for _, right in reversed(edges)]
    )
    result = {
        "method": "typed phrase graph with online one-edge growth",
        "candidate": audit(candidate, edges, trace),
        "edge_count": len(edges),
        "growth_trace": trace,
        "controls": {
            "incumbent_letters": 156,
            "intact": ["The pilot maps the chart near the harbor."],
            "shuffle_seed": 20260929,
        },
        "next_operator": "replace one copular-return growth edge with a non-copular transitive scene clause while preserving its live boundary tape",
    }
    out = Path(__file__).parents[1] / "runs" / "typed-phrase-graph-growth-20260929.json"
    out.write_text(json.dumps(result, indent=2) + "\n")
    return result


if __name__ == "__main__":
    result = run()
    candidate = result["candidate"]
    print(candidate["text"])
    print(json.dumps({k: candidate[k] for k in ("letters", "exact_two_pointer", "validator", "sha256", "reader_gate")}, indent=2))
