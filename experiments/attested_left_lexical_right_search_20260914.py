"""Mine natural left clauses and independently resegment their reverse tape.

The attested corpus is used only to propose *left-side* phrase shapes.  The
right side is generated by a fresh dynamic-programming segmentation over the
fixed conventional lexicon, so no catalogue palindrome or paired catalogue
sentence is copied into an output.  Exactness, anti-shortcut checks, and a
separate POS-shape witness are recorded for every result; none is a readability
certificate.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
import hashlib
import json
from pathlib import Path
import sys

from nltk.corpus import brown
from wordfreq import zipf_frequency

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from llm_palindrome.admission import mechanical_admission_checks, normalize_letters
from llm_palindrome.respace import respace_k
from llm_palindrome.syntax import brown_tables, sentence_like


def lexicon() -> set[str]:
    from llm_palindrome.lexicon import load_lexicon, is_real_word
    from wordfreq import top_n_list

    headwords = load_lexicon(str(ROOT / "data" / "lexicon.txt"))
    observed = set(top_n_list("en", 100_000))
    observed.update(word.lower() for word in brown.words())
    return {
        word for word in observed
        if word.isalpha() and word.isascii() and 2 <= len(word) <= 20
        and zipf_frequency(word, "en") >= 2.6
        and is_real_word(word, headwords)
    } | {"a", "i"}


def source_spans(vocab: set[str], min_words: int, max_words: int,
                 min_letters: int, max_letters: int) -> list[dict[str, object]]:
    spans: list[dict[str, object]] = []
    for sentence_id, sentence in enumerate(brown.sents()):
        words = [word.lower() for word in sentence if word.isalpha()]
        for start in range(len(words)):
            chosen: list[str] = []
            for end in range(start, min(len(words), start + max_words)):
                word = words[end]
                if word not in vocab:
                    break
                chosen.append(word)
                tape = "".join(chosen)
                if len(tape) > max_letters:
                    break
                if min_words <= len(chosen) and len(tape) >= min_letters:
                    spans.append({"sentence_id": sentence_id, "start": start,
                                  "end": end + 1, "words": tuple(chosen),
                                  "text": " ".join(chosen), "letters": tape})
    return spans


def run(*, min_words: int, max_words: int, min_letters: int,
        max_letters: int, k: int, limit: int) -> dict[str, object]:
    vocab = lexicon()
    spans = source_spans(vocab, min_words, max_words, min_letters, max_letters)
    table, shapes, _ = brown_tables()
    rows: list[dict[str, object]] = []
    seen: set[tuple[str, tuple[str, ...]]] = set()
    for span in spans:
        left = tuple(span["words"])
        reverse_tape = str(span["letters"])[::-1]
        for right in respace_k(reverse_tape, vocab, k=k):
            if len(right) < min_words or not sentence_like(right, table, shapes):
                continue
            key = (str(span["letters"]), tuple(right))
            if key in seen:
                continue
            seen.add(key)
            text = " ".join(left + tuple(right))
            checks = mechanical_admission_checks(text, min_letters=30, max_letters=500)
            checks["independent_exact_audit"] = normalize_letters(text) == normalize_letters(text)[::-1]
            checks["left_attested_only"] = True
            rows.append({
                "text": text,
                "left": " ".join(left),
                "right": " ".join(right),
                "letters": len(normalize_letters(text)),
                "source_span": {k: (list(v) if isinstance(v, tuple) else v)
                                for k, v in span.items()},
                "checks": checks,
                "mechanically_eligible": all(checks.values()),
                "reader_status": "not_run",
            })
            if len(rows) >= limit:
                break
        if len(rows) >= limit:
            break
    rows.sort(key=lambda row: (-int(row["letters"]), str(row["text"])))
    return {
        "status": "complete_attested_left_lexical_right_search",
        "config": {"min_words": min_words, "max_words": max_words,
                   "min_letters_per_side": min_letters,
                   "max_letters_per_side": max_letters, "k": k,
                   "limit": limit, "right_side_is_generated_segmentation": True,
                   "machine_readability_certification": False},
        "source": "NLTK Brown spans used as left-side proposal material only",
        "vocabulary_size": len(vocab),
        "vocabulary_sha256": hashlib.sha256("\n".join(sorted(vocab)).encode()).hexdigest(),
        "indexed_spans": len(spans),
        "records": rows,
        "mechanically_eligible": [row for row in rows if row["mechanically_eligible"]],
        "next_construction_operator_if_empty": (
            "Use a semantic frame over the left-side span, then search a jointly typed right-side "
            "segmentation rather than accepting POS-compatible fragments."
        ),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--min-words", type=int, default=3)
    parser.add_argument("--max-words", type=int, default=8)
    parser.add_argument("--min-letters", type=int, default=12)
    parser.add_argument("--max-letters", type=int, default=32)
    parser.add_argument("--k", type=int, default=12)
    parser.add_argument("--limit", type=int, default=1000)
    args = parser.parse_args()
    if args.out.exists():
        parser.error(f"output already exists: {args.out}")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    result = run(min_words=args.min_words, max_words=args.max_words,
                 min_letters=args.min_letters, max_letters=args.max_letters,
                 k=args.k, limit=args.limit)
    args.out.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps({"out": str(args.out), "indexed_spans": result["indexed_spans"],
                      "records": len(result["records"]),
                      "mechanically_eligible": len(result["mechanically_eligible"])}, sort_keys=True))


if __name__ == "__main__":
    main()
