    p=argparse.ArgumentParser(); p.add_argument("--target",type=int,default=100); p.add_argument("--out",default="runs/lexicon-reverse-edge-chain-20260917.json"); a=p.parse_args()
    print(json.dumps(run(a.target,a.out),indent=2))
