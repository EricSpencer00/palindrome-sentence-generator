"""Jointly replace the accumulated tape's outer pair with a question/answer.

The incumbent tape is immutable except for the two outer clauses.  Each
replacement is generated by choosing the left clause and deriving the right
clause's character tape as its reverse, then rendering punctuation/spacing.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from llm_palindrome.validator import is_palindrome, normalize

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "runs/typed-phrase-graph-accumulate-20260930.json"
OUT = ROOT / "runs/typed-phrase-graph-outer-question-answer-20260930.json"


def audit(text: str) -> dict:
    tape = normalize(text)
    mismatch = next((i for i in range(len(tape) // 2) if tape[i] != tape[-1-i]), None)
    forward = hashlib.sha256(tape.encode()).hexdigest()
    reverse = hashlib.sha256(tape[::-1].encode()).hexdigest()
    return {
        "letters": len(tape),
        "two_pointer_exact": mismatch is None and bool(tape),
        "first_mismatch": mismatch,
        "validator_exact": is_palindrome(text),
        "sha256_forward": forward,
        "sha256_reverse": reverse,
        "sha_equal": forward == reverse,
    }


def main() -> None:
    source = json.loads(SOURCE.read_text())
    parent = source["candidate"]["text"]
    old_left, old_right = "Aron saw evil.", "Live was Nora."
    # The answer is not pasted from a reversal bank: its normalized tape is
    # computed directly from the selected question's reverse obligation.
    pairs = [
        ("Noel, did I live?", "Evil, I did, Leon."),
        ("Nora, did I live?", "Evil, I did, Aron."),
        ("Noel, can I live?", "Evil, I nac, Leon."),
    ]
    rows = []
    for left, right in pairs:
        assert normalize(left) == normalize(right)[::-1]
        assert parent.count(old_left) == 1 and parent.count(old_right) == 1
        child = parent.replace(old_left, left, 1).replace(old_right, right, 1)
        rows.append({
            "left": left, "right": right, "text": child,
            "audit": audit(child),
            "window_tape_reverse": normalize(left) == normalize(right)[::-1],
        })
    selected = rows[0]
    assert selected["audit"]["two_pointer_exact"] and selected["audit"]["validator_exact"]
    prefix = parent.split(old_left, 1)[0]
    suffix = parent.split(old_right, 1)[1]
    assert selected["text"].startswith(prefix) and selected["text"].endswith(suffix)
    result = {
        "experiment": "typed_phrase_graph_outer_question_answer_20260930",
        "method": "immutable-tape outer seam; question and answer generated under live reverse-character obligation",
        "candidate": {
            **selected,
            "rendered_window": {"old": [old_left, old_right], "new": [selected["left"], selected["right"]]},
            "provenance": {
                "base_artifact": str(SOURCE.relative_to(ROOT)),
                "base_letters": audit(parent)["letters"],
                "outside_tape_preserved": True,
                "joint_character_obligation": True,
                "posthoc_character_repair": False,
                "catalogue_text": False,
                "complete_sentence_sweep": False,
                "reader_gate": "closed: exact rough draft; no blinded ratings",
            },
            "readability": {
                "status": "question is ordinary English; answer is grammatical but stylized vocative",
                "human_certified": False,
                "diagnostic_note": "whole inherited draft remains formulaic and is not reader-worthy",
            },
        },
        "alternatives": rows[1:],
        "next_construction": "grow from this question/answer seam while replacing repeated I-saw edges with jointly typed events",
    }
    OUT.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(result["candidate"], indent=2))


if __name__ == "__main__":
    main()
