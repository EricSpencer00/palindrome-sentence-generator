"""Small authored repair for the fragmentary discourse palindrome.

The center is always a finite predicate complement (subject + finite verb +
object), selected independently from the surrounding discourse clauses.  This
is deliberately small: it tests grammatical replacement, not another broad
Cartesian sweep, and never reverses a finished word/tape.
"""
from __future__ import annotations
import argparse, hashlib, json
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from llm_palindrome.admission import mechanical_admission_checks, normalize_letters

LEFT = (
    "Was Noel an era,",
    "A poet saw dawn,",
    "Diana read a note,",
    "The nurse heard rain,",
    "Leon wrote a poem,",
)
RIGHT = (
    "a gas.", "a saga.", "a quiet room.", "the old sea.", "a red rose.",
)
# Complete finite propositions, authored as ordinary English rather than
# generated by mirroring any surrounding tape.
CENTERS = (
    "the poet reads a poem",
    "the nurse hears the rain",
    "Diana writes a letter",
    "Noel sees the sea",
    "a teacher marks the map",
    "the editor reads the note",
    "Leon helps the nurse",
    "a poet inspires Diana",
)

def audit(text: str) -> dict:
    t = normalize_letters(text); r = t[::-1]
    mis = [(i, len(t)-1-i) for i in range(len(t)//2) if t[i] != t[-1-i]]
    f = hashlib.sha256(t.encode()).hexdigest(); b = hashlib.sha256(r.encode()).hexdigest()
    return {"letters":len(t), "two_pointer_exact":not mis,
            "mismatch_count":len(mis), "first_mismatch":mis[0] if mis else None,
            "sha256_forward":f, "sha256_reverse":b,
            "sha_equal_under_reversal":f == b}

def run(max_probes=200):
    rows=[]; exact=[]; checked=0
    for li,left in enumerate(LEFT):
        for ci,center in enumerate(CENTERS):
            for ri,right in enumerate(RIGHT):
                checked += 1
                text=f"{left} {center}; {right}"
                a=audit(text); checks=mechanical_admission_checks(text,min_letters=30,max_letters=240)
                row={"rendered":text,"left_index":li,"center_index":ci,"right_index":ri,
                     "provenance":{"left_clause":left,"finite_predicate":center,"right_clause":right,
                                    "center_is_complete_finite_predicate":True,
                                    "direct_reversal_used":False},"audit":a,
                     "mechanical_checks":checks,"independent_exact":a["two_pointer_exact"],
                     "mechanically_admitted":a["two_pointer_exact"] and all(checks.values()),
                     "reader_status":"not_run; programmatic checks do not certify readability"}
                rows.append(row)
                if a["two_pointer_exact"]: exact.append(row)
                if checked>=max_probes: break
            if checked>=max_probes: break
        if checked>=max_probes: break
    admitted=[x for x in exact if x["mechanically_admitted"]]
    return {"status":"finite_predicate_complement_bounded",
            "experiment_id":"finite-predicate-complement-20260918",
            "signature":"authored-discourse|complete-finite-predicate-center|independent-seam-equations",
            "config":{"left_count":len(LEFT),"center_count":len(CENTERS),"right_count":len(RIGHT),"max_probes":max_probes},
            "stats":{"worlds_checked":checked,"exact":len(exact),"mechanically_admitted":len(admitted),"reader_eligible":0},
            "rendered_candidates_and_probes":rows,"exact_candidates":exact,"admitted":admitted,
            "provenance":{"finished_tape_reversed":False,"fragment_center_replaced":True,
                           "catalogue_text_imported":False,"independent_validator":"two-pointer plus forward/reverse SHA-256",
                           "human_readability_certified":False},
            "next_repair":"solve the center predicate token-by-token against residual outer characters, preserving subject–verb agreement and held-out scene roles",
            "reader_gate":"closed until exact candidate survives intact-prose review and randomized blinded controls"}

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--out',required=True,type=Path); ap.add_argument('--max-probes',type=int,default=200); a=ap.parse_args()
    if a.out.exists(): ap.error(f'refusing to overwrite existing output: {a.out}')
    d=run(a.max_probes); a.out.parent.mkdir(parents=True,exist_ok=True); a.out.write_text(json.dumps(d,indent=2)+'\n'); print(json.dumps(d['stats'],indent=2))
if __name__=='__main__': main()
