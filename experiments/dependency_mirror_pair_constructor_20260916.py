"""Joint dependency-mirror construction.

Unlike phrase inventories, this lane starts with two typed dependency trees and
realizes their arguments together.  The reverse-tape equation is consulted at
each complete lexicalization, but neither side is generated by reversing the
other or by resegmenting an already completed tape.
"""
from __future__ import annotations
import hashlib, json, sys
from itertools import product
from pathlib import Path
from collections import Counter
sys.path.insert(0, str(Path(__file__).parents[1]))
from llm_palindrome.admission import mechanical_admission_checks, normalize_letters, tokenize

ROOT = Path(__file__).parents[1]
EXPERIMENT_ID = "dependency-mirror-pair-constructor-20260916"
SIGNATURE = "typed-dependency-head-argument-pairs|joint-two-tree-realization|reverse-tape-equation|argument-order-preservation|heldout-dependency-repair|independent-two-pointer-hash-audit"
OUT = ROOT / "runs" / f"{EXPERIMENT_ID}.json"
REGISTRY = ROOT / "docs" / "experiment-novelty-registry.json"

# Each tuple is a complete dependency tree: subject -> head verb -> object,
# with an optional adjunct attached to the verb.  The lexical alternatives are
# independently authored and are never populated from a text catalogue.
TREES = [
    {"name":"courier_delivery", "subject":["the patient courier","the careful driver","the young clerk"], "verb":["delivers","carries","records"], "object":["the sealed letter","a small parcel","the old ledger"], "adjunct":["for the waiting child before dusk","near the station after the rain","for the quiet nurse before noon"]},
    {"name":"keeper_watch", "subject":["the quiet keeper","the kind nurse","the tired teacher"], "verb":["opens","checks","marks"], "object":["the wooden gate","a clean chart","the lesson book"], "adjunct":["for the waiting child at first light","by the window after the rain","for the patient courier before noon"]},
]

def tape(s: str) -> str: return normalize_letters(s)
def two_pointer(s: str) -> dict:
    t=tape(s); m=next(((i,t[i],t[-1-i]) for i in range(len(t)//2) if t[i]!=t[-1-i]),None)
    return {"algorithm":"independent-two-pointer","letters":len(t),"exact":bool(t) and m is None,"first_mismatch":m}
def hash_audit(s: str) -> dict:
    t=tape(s); h=lambda x:hashlib.sha256(x.encode()).hexdigest()
    return {"algorithm":"sha256-forward-reverse","forward":h(t),"reverse":h(t[::-1]),"exact":bool(t) and h(t)==h(t[::-1])}
def novelty_preflight() -> dict:
    rows=json.loads(REGISTRY.read_text()).get("entries",[])
    collision=any(r.get("id")!=EXPERIMENT_ID and r.get("signature")==SIGNATURE for r in rows)
    return {"entries_inspected":len(rows),"exact_signature_collision":collision,"passed":not collision,"reason":"typed dependency trees are jointly lexicalized under one equation" if not collision else "exact signature already registered"}
def render(tree, vals):
    s,v,o,a=vals
    return f"{s} {v} {o} {a}."
def dependency_record(tree, vals):
    s,v,o,a=vals
    return {"tree":tree["name"],"dependencies":[{"head":v,"relation":"nsubj","dependent":s},{"head":v,"relation":"obj","dependent":o},{"head":v,"relation":"obl","dependent":a}],"agreement":"third-person-singular-present","argument_order":["subject","verb","object","adjunct"]}
def equation(left,right):
    l,r=tape(left),tape(right); n=min(len(l),len(r)); m=next(((i,l[i],r[-1-i]) for i in range(n) if l[i]!=r[-1-i]),None)
    return {"left_letters":len(l),"right_letters":len(r),"equation":"left == reverse(right)","first_mismatch":m,"closed":len(l)==len(r) and m is None,"residual_left":dict(Counter(l)-Counter(r[::-1])),"residual_right":dict(Counter(r[::-1])-Counter(l))}
def row(left_tree,lv,right_tree,rv,repair=None):
    left,right=render(left_tree,lv),render(right_tree,rv)
    eq=equation(left,right)
    return {"rendered":left,"paired_rendered":right,"letters":len(tape(left)),"paired_letters":len(tape(right)),"equation":eq,"dependency_provenance":{"left":dependency_record(left_tree,lv),"right":dependency_record(right_tree,rv)},"audit":{"left_two_pointer":two_pointer(left),"right_two_pointer":two_pointer(right),"left_hash":hash_audit(left),"right_hash":hash_audit(right)},"admission":{"left":mechanical_admission_checks(left,min_letters=39,max_letters=300),"right":mechanical_admission_checks(right,min_letters=39,max_letters=300),"complete_prose":left.endswith(".") and right.endswith(".")},"provenance":{"source":"independently authored typed dependency trees","catalogue_text_used":False,"word_order_mirrored":False,"repeated_unit_shortcut":False,"repair":repair}}
def run():
    pre=novelty_preflight(); rows=[]
    # Joint search: choose a left and right complete dependency realization,
    # score only after both are grammatical, then retain distinct tree pairs.
    for lt,rt in product(TREES, repeat=2):
        best=None
        for lv in product(*[lt[k] for k in ("subject","verb","object","adjunct")]):
            for rv in product(*[rt[k] for k in ("subject","verb","object","adjunct")]):
                q=equation(render(lt,lv),render(rt,rv)); score=(0 if q["closed"] else 1, len(q["residual_left"])+len(q["residual_right"]), abs(q["left_letters"]-q["right_letters"]), q["first_mismatch"][0] if q["first_mismatch"] else 999)
                if best is None or score<best[0]: best=(score,lv,rv)
        rows.append(row(lt,best[1],rt,best[2]))
    # Held-out repair changes one typed dependent on each side and recomputes
    # the complete equation, preserving the dependency relation and order.
    base=rows[0]; lt,rt=TREES[0],TREES[0]
    lv=("the patient courier","delivers","the sealed letter","for the waiting child before dusk")
    rv=("the quiet keeper","opens","the wooden gate","for the waiting child at first light")
    repair=row(lt,lv,rt,("the careful driver","carries","the sealed letter","near the station after the rain"),repair={"operator":"heldout-nsubj-and-adjunct-relexicalization","from":base["equation"]["first_mismatch"],"next":"author a held-out object realization that closes the remaining dependency-pair residual, then run blinded intact-versus-shuffled reader test"})
    result={"experiment_id":EXPERIMENT_ID,"signature":SIGNATURE,"novelty_preflight":pre,"operator":"joint complete dependency-tree lexicalization with typed argument order and global reverse-tape equation","candidate_count":len(rows),"closure_count":sum(r["equation"]["closed"] for r in rows),"best_actual_prose":max(rows,key=lambda r:r["letters"]),"candidates":rows,"repair":[repair],"reader_eligible":False,"status":"completed_no_exact_closure","next_repair":"held-out typed object/adjunct substitution against the recorded dependency residual"}
    OUT.write_text(json.dumps(result,indent=2)+"\n"); return result
if __name__=="__main__":
    r=run(); print(json.dumps({"experiment_id":r["experiment_id"],"novelty":r["novelty_preflight"],"candidates":r["candidate_count"],"closures":r["closure_count"],"best":r["best_actual_prose"]["rendered"]},indent=2))
