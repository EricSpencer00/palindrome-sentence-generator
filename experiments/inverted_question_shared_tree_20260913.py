"""Root-specific single-tree search for ``Was it ... I saw?`` palindromes.

The fixed question envelope is ordinary English and supplies the compatible
outer character contact ``wasi``.  Its interior is generated by a recursive
feature grammar: typed noun phrases may carry nested object-gap relatives;
agreement and transitive valency are represented in the symbols themselves.
The exact search expands one connected derivation tree and emits only its
outermost terminal leaves, retaining a character residual across word
boundaries.  It never generates or stitches two halves.
"""
