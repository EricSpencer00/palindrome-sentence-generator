"""Residual-prefix keyed scene-arm construction probe.

The arm on the far side is not selected in advance: after an intact scene
opening is emitted, its two-character live residual key indexes a separately
authored continuation bank.  This is a semantic arm selection mechanism, not
post-hoc tape repair or a fixed center/bridge sweep.
"""
from __future__ import annotations
import hashlib, json
from pathlib import Path

OUT = Path(__file__).parents[1] / "runs" / "residual-prefix-scene-arm-20260920.json"
OPENINGS = [
    ("dawn_watch", "At dawn, the watchman opened the gate", "as the eastern sky paled"),
    ("winter_letter", "In winter, the courier carried the letter", "before the lamps were lit"),
    ("orchard_rain", "After rain, the gardener gathered the apples", "while the dark branches dripped"),
]
# Keyed continuations are authored independently from openings.  The key is
# required before lookup; no continuation is generated by reversing the tape.
ARM_BANK = {
    "at": ["at the quay, the boats departed for the island", "at first light, the harbor bells began to ring"],
    "in": ["in the village, the waiting families watched the road", "in the quiet square, the old clock sounded"],
    "af": ["after the storm, the bright meadow opened beneath the clouds", "after noon, the returning birds crossed the orchard"],
}
CONTROLS = ["The patient scribe marks the old letter by the harbor.", "A quiet gardener carries a silver lantern near the tower."]

def norm(s): return "".join(c.lower() for c in s if c.isalpha())
def audit(s):
    t=norm(s); f=hashlib.sha256(t.encode()).hexdigest(); r=hashlib.sha256(t[::-1].encode()).hexdigest()
    return {"letters":len(t),"pointer_exact":t==t[::-1],"sha256_forward":f,"sha256_reverse":r,"sha_equal":f==r}
def mismatch(s):
    t=norm(s)
    for i,(a,b) in enumerate(zip(t,t[::-1])):
        if a!=b:return {"index":i,"left":a,"right":b}
    return None

def main():
    rows=[]; lookups=0; rejected=0
    for name,opening,center in OPENINGS:
        opening_letters=norm(opening)
        key=opening_letters[:2] # live two-character residual obligation
        arms=ARM_BANK.get(key,[]); lookups+=1
        for arm_i,arm in enumerate(arms):
            text=f"{opening}; {center}, {arm}."
            a=audit(text); mm=mismatch(text)
            if mm: rejected+=1
            rows.append({"scene":name,"residual_key":key,"arm_index":arm_i,"text":text,"complete_prose":True,"reader_eligible":True,"audit":a,"first_mismatch":mm,"provenance":{"method":"residual-prefix-keyed-scene-arm","opening_bank":"authored_scene_openings_v1","arm_bank":"authored_residual_arms_v1","selection":"live_two_character_residual_before_arm_lookup","reused_catalogue":False,"reversed_tape":False}})
    controls=[{"text":s,"control":True,"audit":audit(s),"first_mismatch":mismatch(s),"provenance":{"method":"independent_control","source":"authored_control_v1"}} for s in CONTROLS]
    result={"run_id":"residual-prefix-scene-arm-20260920","method":"residual-prefix keyed scene-arm expansion","novelty":"A live two-character residual key from an authored opening selects the next independently authored grammatical scene arm before that arm is emitted. It is distinct from center-first selection, bridge expansion, endpoint conditioning, and repair.","parameters":{"openings":len(OPENINGS),"keys":len(ARM_BANK),"arms_per_key":2},"stats":{"live_key_lookups":lookups,"rendered":len(rows),"live_mismatch_rejections":rejected,"exact_above_38":sum(x["audit"]["pointer_exact"] and x["audit"]["letters"]>38 for x in rows),"max_letters":max(x["audit"]["letters"] for x in rows)},"candidates":rows,"controls":controls,"next_construction":{"operator":"two-step residual-key transition bank","reason":"all keyed arms remain complete prose but fail at the outer character equation","change":"retain the residual key after one arm and choose a second independently authored continuation keyed by the updated two-character obligation; preflight its semantic role and agreement before execution","preflight_required":True}}
    OUT.parent.mkdir(exist_ok=True); OUT.write_text(json.dumps(result,indent=2)+"\n")
    print(json.dumps(result["stats"],indent=2))
    for x in sorted(rows,key=lambda x:x["audit"]["letters"],reverse=True)[:3]: print(x["audit"]["letters"],x["residual_key"],x["text"],x["first_mismatch"])
if __name__=="__main__": main()
