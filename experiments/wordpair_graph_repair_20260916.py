"""Lane-9 constructive repair: fresh clause pairs, residual-led composition.

The two sides are authored independently; no side is generated by reversing or
reordering the other. The run records both pointer implementations and a
separate digest so a later repair can target the first residual mismatch.
"""
from pathlib import Path
import hashlib, json, sys
sys.path.insert(0, str(Path(__file__).parents[1]))
from llm_palindrome.wordpair_graph import WordPair, tape

PAIRS = [
 WordPair("At dusk, Mira lights the lantern", "Before dawn, Tomas folds the chart"),
 WordPair("The river carries a quiet reflection", "A distant bell answers across water"),
 WordPair("We mark the trail beside the cedar", "Then small birds settle near the gate"),
 WordPair("Our maps grow warm beneath patient hands", "The old compass rests beside the fire"),
]

def two_pointer(a, b):
    """Compare tapes without constructing a reversed sentence."""
    i, j = 0, len(b)-1
    while i < len(a) and j >= 0 and a[i] == b[j]: i += 1; j -= 1
    return {"equal": i == len(a) and j < 0, "matched": i,
            "left_remaining": a[i:], "right_remaining": b[:j+1]}

def main():
    left = ' '.join(p.left for p in PAIRS)
    right = ' '.join(p.right for p in reversed(PAIRS))
    lt, rt = tape(left), tape(right)
    pointer = two_pointer(lt, rt)
    # Independent hash audit: hash each tape and the rendered candidate.
    hashes = {"left": hashlib.sha256(lt.encode()).hexdigest(),
              "right": hashlib.sha256(rt.encode()).hexdigest(),
              "rendered": hashlib.sha256(tape(left+' '+right).encode()).hexdigest()}
    text = left + ' ' + right
    out = {"method":"constructive_wordpair_residual_repair_v1",
      "candidate":{"text":text,"letters":len(tape(text)),"exact":pointer["equal"],
                   "admitted":pointer["equal"] and len(tape(text))>100,
                   "pointer_audit":pointer,"hash_audit":hashes},
      "provenance":{"inventory":"four fresh, independently authored finite clauses",
                     "composition":"left tape appends; independently authored right tape prepends",
                     "excluded":"catalogue lookup, self-palindrome, word-order symmetry, duplicate sweep"},
      "novelty_preflight":{"tape_sha256":hashes["rendered"],"action":"compare against prior run hashes before publication"},
      "next_repair":"Repair the 1st unmatched boundary by replacing only the adjacent independently authored clause pair; preserve scene semantics and re-run both pointer and hash audits."}
    path=Path(__file__).parents[1]/'runs/wordpair-graph-repair-2026-09-16.json'
    path.write_text(json.dumps(out,indent=2)+'\n'); print(json.dumps({'output':str(path),'letters':len(tape(text)),'exact':pointer['equal']}))
if __name__ == '__main__': main()
