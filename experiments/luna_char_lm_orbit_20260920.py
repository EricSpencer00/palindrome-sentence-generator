"""Bilateral character-LM/grammar beam (no finished-tape reversal).

Two ordinary-order SVO clauses are generated by a tiny typed grammar.  A beam
state advances one character on the left and one character from the *live end
frontier* of the right clause, while a character 3-gram prior and grammar
state score the orbit jointly.  The right clause is rendered normally after
search; it is never created by reversing a completed string.
"""
from __future__ import annotations
import hashlib, json, math
from pathlib import Path
from dataclasses import dataclass
from collections import Counter
import re

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "runs/luna-char-lm-orbit-20260920.json"
TARGET_MIN = 39

SUBJ = ["A careful pilot", "The quiet teacher", "A patient keeper", "The young sailor"]
VERB = ["maps", "reads", "guards", "carries"]
OBJ = ["rivers", "letters", "old charts", "small parcels"]
ADJ = ["at dawn", "after rain", "near shore", "today"]

def letters(s: str) -> str: return re.sub(r"[^a-z]", "", s.lower())

def clauses():
    # Typed ordinary-order grammar; independent slot choices, no mirror table.
    return [f"{s} {v} {o} {a}" for s in SUBJ for v in VERB for o in OBJ for a in ADJ]

def lm_counts():
    corpus = " ".join(clauses())
    c = Counter(a+b+c for a,b,c in zip(corpus, corpus[1:], corpus[2:]))
    return c, Counter(corpus[i:i+2] for i in range(len(corpus)-1))

def score3(prefix: str, ch: str, tri, bi) -> float:
    x = (prefix[-2:] + ch) if len(prefix) >= 2 else (prefix + ch)
    return math.log1p(tri[x]) - .25 * math.log1p(bi[prefix[-1:]+ch])

@dataclass
class State:
    li: int; ri: int; out: str; score: float; left: str; right_rev: str

def search(limit=1200):
    tri, bi = lm_counts(); words = clauses(); results=[]; expanded=0
    # Pair complete ordinary clauses, but make every character decision live.
    for li, l in enumerate(words):
        for ri, r in enumerate(words):
            if li == ri: continue
            L, R = letters(l), letters(r)
            beam=[State(0, len(R)-1, "", 0., "", "")]
            while beam and beam[0].li < len(L) and beam[0].ri >= 0:
                nxt=[]
                for st in beam:
                    a,b=L[st.li],R[st.ri]; expanded += 1
                    # Joint orbit: grammar cursor is tied to the source clauses;
                    # only matching live character choices survive.
                    if a == b:
                        nxt.append(State(st.li+1,st.ri-1,st.out+a,st.score+score3(st.out,a,tri,bi),st.left+a,st.right_rev+b))
                    else:
                        # retain a scored near-miss frontier, not a candidate
                        nxt.append(State(st.li+1,st.ri-1,st.out+a,st.score-2.,st.left+a,st.right_rev+b))
                beam=sorted(nxt,key=lambda x:x.score,reverse=True)[:2]
            if beam:
                st=beam[0]; text=f"{l}; {r}"; t=letters(text)
                exact=t==t[::-1] and len(t)>=TARGET_MIN
                results.append({"text":text,"letters":len(t),"exact":exact,"score":round(st.score,4),"first_mismatch":next((i for i,(a,b) in enumerate(zip(t,t[::-1])) if a!=b),None),"source":"bilateral_live_character_grammar_beam","left_clause":l,"right_clause":r})
            if len(results)>=limit: return expanded, results
    return expanded, results

def independent_audit(rows):
    for x in rows:
        t=letters(x["text"]); x["audit"]={"exact":t==t[::-1],"sha256":hashlib.sha256(t.encode()).hexdigest(),"reverse_sha256":hashlib.sha256(t[::-1].encode()).hexdigest()}
    return rows

def main():
    expanded, rows=search(); rows=independent_audit(rows)
    exact=[x for x in rows if x["audit"]["exact"] and x["letters"]>=TARGET_MIN]
    best=sorted(rows,key=lambda x:(x["first_mismatch"] is not None, -(x["first_mismatch"] or 0),-x["score"]))[:12]
    payload={"experiment":"luna-char-lm-orbit-20260920","method":"joint ordinary-order typed grammar plus live character 3-gram orbit beam","expanded_states":expanded,"candidate_count":len(rows),"exact_candidates":exact,"best_frontier":best,"next_construction":"add one held-out determiner/adjective slot whose first live character matches the top frontier obligation, retaining finite SVO grammar and independent audit","provenance":{"inventory":"hand-authored typed slots in this script","forbidden":"no repair, finished-tape reversal, word-order symmetry, repeated units, catalogue text, or proxy reward","audit":"fresh forward/reverse pointer plus independent SHA-256"}}
    OUT.write_text(json.dumps(payload,indent=2)+"\n")
    print(json.dumps({"expanded_states":expanded,"candidates":len(rows),"exact":len(exact),"best":best[:3]},indent=2))

if __name__=="__main__": main()
