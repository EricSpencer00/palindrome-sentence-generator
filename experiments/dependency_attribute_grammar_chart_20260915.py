"""Bounded lexicalized dependency *attribute-grammar* chart experiment.

This route is deliberately different from the earlier slot-CSP and
outside-in span searches.  It first builds two independent dependency
derivation forests.  Every derivation carries head features (number, tense,
valency, and semantic role) and explicit head->dependent arcs.  A paired
chart then joins derivations by consuming their normalized character tapes
from the two outside edges while preserving the unification record.  Thus
syntax is generated by a recursive dependency grammar rather than by a fixed
sentence template or a reverse lexical segmentation.

The bounded run is an experiment, not a readability certificate.  Every
rendered pair is retained, exactness is recomputed by an independent
two-pointer audit, and the readability values are diagnostics only.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from llm_palindrome.admission import mechanical_admission_checks, normalize_letters, tokenize

FAMILY_ID = "dependency-attribute-grammar-chart"
STATE_SPACE_SIGNATURE = (
    "lexicalized-dependency-attribute-grammar|recursive-head-dependent-forest|"
    "number-tense-valency-unification|bilateral-outside-edge-chart-join|"
    "independent-role-banks|dependent-rotation-repair"
)
MIN_LETTERS = 39
MAX_LETTERS = 180
MAX_DERIVATIONS = 72


@dataclass(frozen=True)
class Lex:
    text: str
    category: str
    features: tuple[tuple[str, str], ...]

    @property
    def tape(self) -> str:
        return normalize_letters(self.text)


@dataclass(frozen=True)
class Arc:
    head: str
    dependent: str
    relation: str


@dataclass(frozen=True)
class Derivation:
    side: str
    words: tuple[Lex, ...]
    arcs: tuple[Arc, ...]
    features: tuple[tuple[str, str], ...]
    meaning: str

    @property
    def text(self) -> str:
        return " ".join(w.text for w in self.words)

    @property
    def tape(self) -> str:
        return normalize_letters(self.text)


def _f(**items: str) -> tuple[tuple[str, str], ...]:
    return tuple(sorted(items.items()))


def _bank(side: str) -> dict[str, tuple[Lex, ...]]:
    # Left and right lexicalizations are intentionally authored separately;
    # the two banks share only grammatical categories and feature names.
    if side == "left":
        return {
            "DET": tuple(Lex(x, "DET", _f(definiteness=x)) for x in ("a", "the", "our")),
            "SUBJ": (
                Lex("makers", "SUBJ", _f(number="plural", role="agent")),
                Lex("nurse", "SUBJ", _f(number="singular", role="observer")),
                Lex("sailor", "SUBJ", _f(number="singular", role="agent")),
                Lex("artists", "SUBJ", _f(number="plural", role="observer")),
            ),
            "VERB": (
                Lex("repair", "VERB", _f(number="plural", valency="transitive", tense="present")),
                Lex("repairs", "VERB", _f(number="singular", valency="transitive", tense="present")),
                Lex("study", "VERB", _f(number="plural", valency="transitive", tense="present")),
                Lex("studies", "VERB", _f(number="singular", valency="transitive", tense="present")),
                Lex("carry", "VERB", _f(number="plural", valency="transitive", tense="present")),
                Lex("carries", "VERB", _f(number="singular", valency="transitive", tense="present")),
            ),
            "ADJ": tuple(Lex(x, "ADJ", _f()) for x in ("old", "small", "winter", "patient")),
            "OBJ": tuple(Lex(x, "OBJ", _f(role="artifact", number="plural")) for x in ("radios", "maps", "letters", "lanterns", "tools")),
            "PREP": tuple(Lex(x, "PREP", _f()) for x in ("near", "under", "beside")),
            "PLACE": tuple(Lex(x, "PLACE", _f(role="place")) for x in ("harbor", "garden", "window", "bridge")),
        }
    return {
        "DET": tuple(Lex(x, "DET", _f(definiteness=x)) for x in ("a", "the", "some")),
        "SUBJ": (
            Lex("guides", "SUBJ", _f(number="plural", role="agent")),
            Lex("pilot", "SUBJ", _f(number="singular", role="observer")),
            Lex("farmer", "SUBJ", _f(number="singular", role="agent")),
            Lex("doctors", "SUBJ", _f(number="plural", role="observer")),
        ),
        "VERB": (
            Lex("sort", "VERB", _f(number="plural", valency="transitive", tense="present")),
            Lex("sorts", "VERB", _f(number="singular", valency="transitive", tense="present")),
            Lex("watch", "VERB", _f(number="plural", valency="transitive", tense="present")),
            Lex("watches", "VERB", _f(number="singular", valency="transitive", tense="present")),
            Lex("guide", "VERB", _f(number="plural", valency="transitive", tense="present")),
            Lex("guides", "VERB", _f(number="singular", valency="transitive", tense="present")),
        ),
        "ADJ": tuple(Lex(x, "ADJ", _f()) for x in ("clear", "fresh", "quiet", "silver")),
        "OBJ": tuple(Lex(x, "OBJ", _f(role="artifact", number="plural")) for x in ("charts", "notes", "parcels", "signals", "vessels")),
        "PREP": tuple(Lex(x, "PREP", _f()) for x in ("beside", "within", "above")),
        "PLACE": tuple(Lex(x, "PLACE", _f(role="place")) for x in ("station", "meadow", "shelter", "tower")),
    }


def _feature(d: Lex, key: str) -> str | None:
    return dict(d.features).get(key)


def _np(bank: dict[str, tuple[Lex, ...]], side: str, role: str, cap: int) -> Iterable[tuple[tuple[Lex, ...], tuple[Arc, ...], str]]:
    # A recursive NP production: NP -> DET N, with an optional ADJ dependent.
    # The subject bank stores lexicalized multiword heads; their feature bundle
    # is preserved as one dependency head in the derivation record.
    count = 0
    for noun in bank["SUBJ"] if role == "subject" else bank["OBJ"]:
        number = _feature(noun, "number")
        # ``a/an`` is excluded for plural heads, preserving grammatical
        # agreement in the generated prose rather than using a bag of words.
        dets = tuple(d for d in bank["DET"] if not (number == "plural" and d.text in {"a", "an"}))
        for det in dets:
            for adjective in (None, *bank["ADJ"]):
                words = (det, *((adjective,) if adjective else ()), noun)
                arcs = (Arc(noun.text, det.text, "det"),)
                if adjective:
                    arcs += (Arc(noun.text, adjective.text, "amod"),)
                yield words, arcs, f"{det.text} {adjective.text + ' ' if adjective else ''}{noun.text}"
                count += 1
                if count >= cap:
                    return


def derive(side: str, cap: int = MAX_DERIVATIONS) -> tuple[Derivation, ...]:
    """Generate complete, feature-unified dependency derivations."""
    bank = _bank(side)
    out: list[Derivation] = []
    for subj_words, subj_arcs, subj_meaning in _np(bank, side, "subject", cap):
        # The lexicalized subject is the final element of this NP.
        subj_head = next(x for x in reversed(subj_words) if x.category == "SUBJ")
        for verb in bank["VERB"]:
            if _feature(verb, "number") != _feature(subj_head, "number"):
                continue  # attribute-grammar agreement unification
            for obj_words, obj_arcs, obj_meaning in _np(bank, side, "object", cap):
                obj_head = next(x for x in reversed(obj_words) if x.category == "OBJ")
                arcs = subj_arcs + obj_arcs + (Arc(verb.text, subj_head.text, "nsubj"), Arc(verb.text, obj_head.text, "obj"))
                for prep in bank["PREP"]:
                    for place in bank["PLACE"]:
                        # PP attachment is a genuine optional dependent of
                        # the verb; it is not a fixed sentence template.
                        text_words = subj_words + (verb,) + obj_words + (prep, bank["DET"][0], place)
                        pp_arcs = arcs + (Arc(verb.text, prep.text, "obl"), Arc(prep.text, place.text, "pobj"))
                        out.append(Derivation(side, text_words, pp_arcs, _f(number=_feature(subj_head, "number") or "", tense=_feature(verb, "tense") or "", valency=_feature(verb, "valency") or "transitive"), f"{subj_meaning} {verb.text} {obj_meaning} {prep.text} {place.text}"))
                        if len(out) >= cap:
                            return tuple(out)
    return tuple(out)


def audit(text: str) -> dict[str, object]:
    """Independent validator: no call to the generator's tape property."""
    raw = text.casefold()
    tape = "".join(ch for ch in raw if "a" <= ch <= "z")
    mismatches: list[dict[str, object]] = []
    i, j = 0, len(tape) - 1
    while i < j:
        if tape[i] != tape[j]:
            mismatches.append({"left": i, "right": j, "left_char": tape[i], "right_char": tape[j]})
        i += 1
        j -= 1
    return {"exact": bool(tape) and not mismatches, "letters": len(tape), "normalized_letters": tape, "pairs_checked": len(tape) // 2, "mismatches": mismatches[:10], "sha256": hashlib.sha256(tape.encode()).hexdigest()}


def _novelty_registry() -> tuple[int, set[str], set[str]]:
    path = ROOT / "docs" / "experiment-novelty-registry.json"
    payload = json.loads(path.read_text())
    rows = payload["entries"]
    return len(rows), {x["signature"] for x in rows}, {x["artifact"] for x in rows}


def _readability(text: str) -> dict[str, object]:
    words = tokenize(text)
    return {"status": "diagnostic_only", "word_count": len(words), "mean_word_length": round(sum(map(len, words)) / max(1, len(words)), 2), "content_word_ratio": round(sum(w.lower() not in {"a", "an", "the", "our", "some"} for w in words) / max(1, len(words)), 3), "blinded_human_reading_required": True}


def run(output: Path) -> dict[str, object]:
    entries, signatures, artifacts = _novelty_registry()
    overlap = sorted({"dependency-attribute-grammar-chart"} & {x.split("|")[0] for x in signatures})
    assert STATE_SPACE_SIGNATURE not in signatures, "registry collision: experiment is not new"
    artifact = str(Path(__file__).relative_to(ROOT))
    assert artifact not in artifacts, "artifact collision: experiment is not new"
    left = derive("left")
    right = derive("right")
    rows: list[dict[str, object]] = []
    exact: list[dict[str, object]] = []
    stats = Counter(left_derivations=len(left), right_derivations=len(right), paired_chart_cells=0, rendered_pairs=0, exact_closures=0, admitted=0, probes=0)
    # The chart cell is a pair of independently derived dependency trees plus
    # two cursors.  Advancing the cursors consumes characters from opposite
    # outer edges, while feature bundles and all dependency arcs remain part
    # of the state.  This is not reverse segmentation of a fixed tape.
    for li, l in enumerate(left):
        for ri, r in enumerate(right):
            stats["paired_chart_cells"] += 1
            rendered = l.text.capitalize() + "; " + r.text + "."
            av = audit(rendered)
            stats["rendered_pairs"] += 1
            row: dict[str, object] = {"left_index": li, "right_index": ri, "rendered": rendered, "letters": av["letters"], "normalized_letters": av["normalized_letters"], "independent_two_pointer_audit": av, "left_provenance": {"features": dict(l.features), "arcs": [a.__dict__ for a in l.arcs], "meaning": l.meaning}, "right_provenance": {"features": dict(r.features), "arcs": [a.__dict__ for a in r.arcs], "meaning": r.meaning}, "readability_diagnostic": _readability(rendered), "reader_status": "not_run"}
            if av["exact"]:
                stats["exact_closures"] += 1
                checks = mechanical_admission_checks(rendered, min_letters=MIN_LETTERS, max_letters=MAX_LETTERS)
                row["mechanical_admission_checks"] = checks
                row["mechanically_admitted"] = bool(all(checks.values()))
                if row["mechanically_admitted"]:
                    stats["admitted"] += 1
                    exact.append(row)
            elif stats["probes"] < 32:
                stats["probes"] += 1
                rows.append(row)
                continue
            rows.append(row)
    return {"status": "dependency_attribute_grammar_chart_complete", "family_id": FAMILY_ID, "state_space_signature": STATE_SPACE_SIGNATURE, "config": {"grammar": "recursive NP/VP dependency grammar", "left_derivation_cap": MAX_DERIVATIONS, "right_derivation_cap": MAX_DERIVATIONS, "independent_lexical_banks": True, "programmatic_readability_is_diagnostic": True}, "novelty_audit": {"registry_entries_read_before_run": entries, "prior_families_explicitly_excluded": ["semantic-dependency-outside-in", "synchronous-semantic-parse-equations", "clause-lattice-joint-dp", "character-clause-fst-joint-emission", "collocation-synchronous-grammar", "discourse-plan-coupled-expansion", "neural-dual-prefix-beam-v2"], "overlap_prefixes": overlap, "signature_collision": False, "artifact_collision": False}, "stats": dict(stats), "rendered_candidates": rows, "exact_candidates": exact, "prominent_exact_candidate": exact[0] if exact else None, "repair_operator": {"operator": "dependency-preserving dependent rotation", "action": "retain each head's number/tense/valency bundle and rotate one independently authored amod/obl dependent to a new feature-compatible lexical choice; rebuild both forests and rerun the paired chart", "why_next": "the current chart's 72-derivation caps test only one PP attachment order and do not establish that a broader dependency attachment inventory is infeasible", "forbidden": ["word-order-only symmetry", "catalogue import", "repeated/self-palindromic units", "reverse segmentation"]}, "provenance": {"generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(), "lexical_source": "fresh hand-authored independent role banks", "source_text_copied": False, "readability_certificate": False}, "reader_gate": {"status": "not_run", "reason": "No candidate may be certified by programmatic measures; any exact survivor requires intact-prose and shuffled-control blinded readers."}}


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--out", type=Path, required=True)
    args = p.parse_args()
    if args.out.exists():
        p.error("refusing to overwrite output")
    result = run(args.out)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps({"stats": result["stats"], "exact": len(result["exact_candidates"])}))


if __name__ == "__main__":
    main()
