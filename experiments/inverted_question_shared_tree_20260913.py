MIN_LETTERS, MAX_LETTERS = 100, 180


@dataclass(frozen=True)
class Noun:
    form: str
    type: str
    number: str


@dataclass(frozen=True)
class Verb:
    form: str
    patient_type: str
    subject_number: str


NOUNS = (
    Noun("portrait", "object", "sing"), Noun("packet", "object", "sing"),
    Noun("artifact", "object", "sing"), Noun("teacher", "person", "sing"),
    Noun("artist", "person", "sing"), Noun("guard", "person", "sing"),
    Noun("writer", "person", "sing"), Noun("singer", "person", "sing"),
    Noun("farmer", "person", "sing"), Noun("nurse", "person", "sing"),
    Noun("pilot", "person", "sing"), Noun("scholar", "person", "sing"),
)
ADJECTIVES = ("quiet", "careful", "patient", "brave", "young", "gentle", "steady", "honest", "alert", "warm")
VERBS = (
    Verb("praised", "object", "sing"), Verb("painted", "object", "sing"),
    Verb("saved", "object", "sing"), Verb("watched", "object", "sing"),
    Verb("greeted", "person", "sing"), Verb("trusted", "person", "sing"),
    Verb("followed", "person", "sing"), Verb("helped", "person", "sing"),
    Verb("met", "person", "sing"), Verb("praised", "person", "sing"),
)


class InvertedQuestionGrammar:
    """A finite recursive CFG with NP type/number and relative valency features."""

    def __init__(self, max_depth: int = 6):
        self.max_depth = max_depth

    def start(self) -> BASE.Symbol:
        return BASE.sym("Q", depth=str(self.max_depth))

    def terminal(self, symbol: BASE.Symbol) -> str | None:
        return symbol.feature("form") if symbol.name == "T" else None

    def productions(self, lhs: BASE.Symbol) -> tuple[BASE.Production, ...]:
        f = dict(lhs.features)
        if lhs.name == "Q":
            return (BASE.Production("Q:was-it-interior-i-saw", lhs, (
                BASE.sym("T", label="fixed_was", form="was"),
                BASE.sym("T", label="fixed_it", form="it"),
                BASE.sym("NP", role="complement", type="object", number="sing", depth=f["depth"]),
                BASE.sym("T", label="fixed_i", form="i"),
                BASE.sym("T", label="fixed_saw", form="saw"),
            )),)
        if lhs.name == "NP":
            role, typ, number, depth = f["role"], f["type"], f["number"], int(f["depth"])
            det = "a" if number == "sing" else "the"
            rows: list[BASE.Production] = []
            for adjective in ADJECTIVES:
                for noun in NOUNS:
                    if noun.type != typ or noun.number != number:
                        continue
                    prefix = (BASE.sym("T", label="det", form=det), BASE.sym("T", label="adj", form=adjective),
                              BASE.sym("T", label=f"noun_{role}", form=noun.form))
                    rows.append(BASE.Production(f"NP:{role}:{typ}:{depth}:{adjective}:{noun.form}:base", lhs, prefix))
                    # Object-gap relatives may modify either an object or a
                    # person NP; the relative verb's patient feature enforces
                    # the corresponding typed valency below.
                    if depth > 0:
                        rows.append(BASE.Production(f"NP:{role}:{typ}:{depth}:{adjective}:{noun.form}:relative", lhs,
                            prefix + (BASE.sym("REL", head_type=typ, depth=str(depth - 1)),)))
            return tuple(rows)
        if lhs.name == "REL":
            depth, head_type = int(f["depth"]), f["head_type"]
            # This is an object-gap relative: it has a subject NP and a
            # transitive verb whose missing patient is the head NP. Recursion
            # proceeds through that subject NP, including person-headed
            # relatives (licensed by the person-patient verb ``greeted``).
            subject = BASE.sym("NP", role="relative_agent", type="person", number="sing", depth=str(depth))
            return tuple(BASE.Production(f"REL:{head_type}:{depth}:{verb.form}", lhs,
                (BASE.sym("T", label="relative_that", form="that"), subject,
                 BASE.sym("V", event="transitive_gap", patient_type=head_type,
                          subject_number=verb.subject_number, form=verb.form)))
                        for verb in VERBS if verb.patient_type == head_type)
        if lhs.name == "V":
            return (BASE.Production(f"V:{lhs.feature('form')}", lhs,
                                    (BASE.sym("T", label="relative_verb", form=lhs.feature("form")),)),)
        return ()

    def digest(self) -> str:
        seen, queue, rows = set(), deque([self.start()]), []
        while queue:
            lhs = queue.popleft()
            if lhs in seen:
                continue
            seen.add(lhs)
            prods = self.productions(lhs)
            rows.append((lhs.name, lhs.features, [(p.identifier, [x.name + str(x.features) for x in p.rhs]) for p in prods]))
            queue.extend(x for p in prods for x in p.rhs if self.terminal(x) is None)
        return sha256(json.dumps(rows, sort_keys=True).encode()).hexdigest()


def parse_tree(grammar: InvertedQuestionGrammar, text: str) -> BASE.Tree | None:
    """Independent chart-style complete reparse with all local alternatives."""
    if text != text.strip() or re.sub(r"[a-z ]", "", text.lower()):
        return None
    tokens = tuple(re.findall(r"[a-z]+", text.lower()))
    memo: dict[tuple[BASE.Symbol, int], tuple[tuple[BASE.Tree, int], ...]] = {}

    def parse_all(symbol: BASE.Symbol, offset: int) -> tuple[tuple[BASE.Tree, int], ...]:
        key = (symbol, offset)
        if key in memo:
            return memo[key]
        terminal = grammar.terminal(symbol)
        if terminal is not None:
            result = ((BASE.Tree(symbol, f"lex:{terminal}", (), terminal), offset + 1),) if offset < len(tokens) and tokens[offset] == terminal else ()
            memo[key] = result
            return result
        answers = []
        for prod in grammar.productions(symbol):
            partials: list[tuple[list[BASE.Tree], int]] = [([], offset)]
            for child in prod.rhs:
                next_partials = []
                for children, cursor in partials:
                    for node, end in parse_all(child, cursor):
                        next_partials.append((children + [node], end))
                partials = next_partials
                if not partials:
                    break
            answers.extend((BASE.Tree(symbol, prod.identifier, tuple(children)), cursor) for children, cursor in partials)
        memo[key] = tuple(answers)
        return memo[key]

    return next((tree for tree, end in parse_all(grammar.start(), 0) if end == len(tokens)), None)


def feature_witness(tree: BASE.Tree | None) -> dict[str, object]:
    roles, relatives, agreement, valency = [], 0, True, True
    def visit(node: BASE.Tree) -> None:
        nonlocal relatives, agreement, valency
        if node.symbol.name == "NP":
            roles.append(dict(node.symbol.features))
        if node.symbol.name == "REL":
            relatives += 1
            if (len(node.children) != 3 or node.children[0].terminal != "that" or
                    node.children[1].symbol.name != "NP" or node.children[2].symbol.name != "V"):
                valency = False
            elif node.children[2].symbol.feature("patient_type") != node.symbol.feature("head_type"):
                valency = False
            elif node.children[1].symbol.feature("number") != node.children[2].symbol.feature("subject_number"):
                agreement = False
        for child in node.children:
            visit(child)
    if tree:
        visit(tree)
    return {"semantic_roles": roles, "relative_count": relatives, "agreement_ok": agreement,
            "valency_ok": valency, "complete_tree": bool(tree and tree.symbol.name == "Q")}


def exact_audit(text: str) -> dict[str, object]:
    tape = "".join(c for c in text.lower() if "a" <= c <= "z")
    mismatches = [(i, len(tape) - i - 1) for i in range(len(tape) // 2) if tape[i] != tape[-i - 1]]
    bounds, cursor = [], 0
    for word in re.findall(r"[a-z]+", text.lower()):
        cursor += len(word); bounds.append(cursor)
    return {"exact": bool(tape) and not mismatches, "letters": len(tape), "mismatches": mismatches,
            "normalized_sha256": sha256(tape.encode()).hexdigest(),
            "shifted_word_boundaries": sorted(set(bounds[:-1]) - {len(tape) - x for x in bounds[:-1]})}


def audit(grammar: InvertedQuestionGrammar, text: str, kind: str, trace: tuple[tuple[int, str], ...], reason: str | None = None) -> dict[str, object]:
    exact, tree = exact_audit(text), parse_tree(grammar, text)
    witness = feature_witness(tree)
    central = mechanical_admission_checks(text, min_letters=MIN_LETTERS, max_letters=MAX_LETTERS)
    codes = [key for key, value in central.items() if not value]
    if tree is None: codes.append("independent_complete_reparse_failed")
    if not witness["agreement_ok"]: codes.append("agreement_failure")
    if not witness["valency_ok"]: codes.append("valency_failure")
    if reason and reason not in codes: codes.append(reason)
    return {"record_kind": kind, "rendered": text, "independent_exact_audit": exact,
            "independent_parse": tree is not None, "feature_witness": witness,
            "central_admission": central, "mechanically_admitted": not codes,
            "rejection_codes": codes, "shared_tree_trace": list(trace),
            "reader_status": "unreviewed; programmatic measures do not certify readability"}


def solver(grammar: InvertedQuestionGrammar, *, max_states: int = 100000, max_records: int = 100) -> dict[str, object]:
    root = BASE.Node(0, grammar.start())
    initial = BASE.State((0,), (root,), (), "", 0, 0, ())
    queue, seen, exact_rows, admitted, rejects = deque([initial]), set(), {}, {}, {}
    stats = Counter(states=0, expansions=0, emissions=0, residual_contradictions=0,
                    complete_trees=0, exact_closures=0, independent_reparse_rejections=0)
    while queue and stats["states"] < max_states:
        state = queue.pop(); stats["states"] += 1
        key = (state.frontier, state.nodes, state.leaves, state.residual, state.owner, state.length)
        if key in seen: continue
        seen.add(key)
        if BASE.complete(state):
            stats["complete_trees"] += 1
            if MIN_LETTERS <= state.length <= MAX_LETTERS and state.residual == state.residual[::-1]:
                text = BASE.render(state); row = audit(grammar, text, "complete_shared_tree_closure", state.trace)
                if row["independent_exact_audit"]["exact"] and row["independent_parse"]:
                    stats["exact_closures"] += 1; exact_rows.setdefault(text, row)
                    if row["mechanically_admitted"]: admitted.setdefault(text, row)
                    elif len(rejects) < max_records:
                        rejects.setdefault(text, row); stats["independent_reparse_rejections"] += 1
            continue
        nodes = BASE.node_map(state)
        unresolved = [i for i, ref in enumerate(state.frontier) if not nodes[ref].terminal]
        if unresolved:
            if not nodes[state.frontier[0]].terminal:
                indices = (0,)
            elif not nodes[state.frontier[-1]].terminal:
                indices = (len(state.frontier) - 1,)
            else:
                indices = (unresolved[0],)
            for index in indices:
                for next_state in BASE.expand(grammar, state, index):
                    queue.append(next_state); stats["expansions"] += 1
        left_leaf = bool(nodes[state.frontier[0]].terminal)
        right_leaf = bool(nodes[state.frontier[-1]].terminal)
        sides = (-state.owner,) if state.residual else (1, -1)
        for side in sides:
            if (side == 1 and not left_leaf) or (side == -1 and not right_leaf): continue
            next_state = BASE.emit(state, side)
            if next_state is not None:
                queue.append(next_state); stats["emissions"] += 1
            else:
                stats["residual_contradictions"] += 1
    return {"stats": dict(stats), "states_exhausted": not queue and stats["states"] < max_states,
            "exact_closures": list(exact_rows.values()), "mechanically_admitted_closures": list(admitted.values()),
            "independent_reparse_rejections": list(rejects.values())}


def explicit_recursive_control(grammar: InvertedQuestionGrammar) -> BASE.State:
    """Construct the six-level relative control by explicit tree choices."""
    root = BASE.Node(0, grammar.start())
    state = BASE.State((0,), (root,), (), "", 0, 0, ())
    for _ in range(1000):
        nodes = BASE.node_map(state)
        unresolved = [i for i, ref in enumerate(state.frontier) if not nodes[ref].terminal]
        if not unresolved:
            return state
        target = next((i for i in unresolved if nodes[state.frontier[i]].symbol.name == "NP"
                       and int(nodes[state.frontier[i]].symbol.feature("depth", "0")) > 0), unresolved[0])
        options = BASE.expand(grammar, state, target)
        if not options:
            return state
        symbol = nodes[state.frontier[target]].symbol
        if symbol.name == "NP":
            depth = int(symbol.feature("depth", "0"))
            role, typ = symbol.feature("role"), symbol.feature("type")
            # Distinct authored content across the six nested levels keeps the
            # diagnostic control from masquerading as a repeated catalogue
            # unit. The grammar still exposes all lexical alternatives.
            person = ("teacher", "artist", "guard", "writer", "singer", "farmer", "nurse")
            noun = person[min(max(grammar.max_depth - depth, 0), len(person) - 1)] if typ == "person" else "portrait"
            adjective = ADJECTIVES[min(max(grammar.max_depth - depth, 0), len(ADJECTIVES) - 1)]
            suffix = ":relative" if depth > 0 else ":base"
            state = next(item for item in options
                         if any(prod.endswith(suffix) and f":{adjective}:{noun}{suffix}" in prod
                                for _, prod in item.trace[-1:]))
        elif symbol.name == "REL":
            depth = int(symbol.feature("depth", "0"))
            person_verbs = ("greeted", "trusted", "followed", "helped", "met")
            wanted = ("watched" if symbol.feature("head_type") == "object" else
                      person_verbs[min(max(grammar.max_depth - depth - 2, 0), len(person_verbs) - 1)])
            state = next(item for item in options if item.trace[-1][1].endswith(wanted))
        else:
            state = options[0]
    raise AssertionError("recursive control did not finish")


def run(*, max_states: int = 100000) -> dict[str, object]:
    grammar = InvertedQuestionGrammar(6)
    result = solver(grammar, max_states=max_states)
    control_state = explicit_recursive_control(grammar)
    control_text = BASE.render(control_state)
    recursive_control = audit(grammar, control_text, "complete_recursive_grammar_control", control_state.trace)
    recursive_control["provenance"] = "task-authored longest depth-six recursive NP/relative derivation; diagnostic control only"
    return {"status": "root_specific_inverted_question_shared_tree_intersection", "config": {
        "min_letters": MIN_LETTERS, "max_letters": MAX_LETTERS, "max_depth": grammar.max_depth,
        "max_states": max_states, "envelope": "Was it ... I saw?", "single_shared_derivation_tree": True,
        "character_residual_during_derivation": True, "closure_requires_all_leaves_consumed": True,
        "independent_complete_reparse": True, "catalogue_used_only_for_central_exclusion": True,
        "corpus_generation": False},
        "provenance": {"generator_sha256": sha256(Path(__file__).read_bytes()).hexdigest(),
                       "grammar_sha256": grammar.digest(), "material": "task-authored fixed question envelope and feature grammar; no catalogue or corpus construction material"},
        "grammar": {"nouns": [asdict(x) for x in NOUNS], "adjectives": ADJECTIVES, "verbs": [asdict(x) for x in VERBS]},
        "complete_recursive_control": recursive_control,
        **result,
        "reader_facing_next_operator": "Increase typed relative depth only after adding a same-tree lexical substitution transducer that preserves the Was-it/I-saw envelope and independent reparse.",
        "scope": "This bounded grammar intersection is not a readability certificate; any exact output would require blinded human evaluation."}


def main() -> None:
    parser = argparse.ArgumentParser(); parser.add_argument("--out", type=Path, required=True); parser.add_argument("--max-states", type=int, default=100000)
    args = parser.parse_args()
    if args.out.exists(): parser.error(f"refusing to overwrite {args.out}")
    result = run(max_states=args.max_states); args.out.parent.mkdir(parents=True, exist_ok=True); args.out.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps({"out": str(args.out), "states": result["stats"]["states"], "exact_closures": len(result["exact_closures"]), "admitted": len(result["mechanically_admitted_closures"])}, indent=2))


if __name__ == "__main__": main()
