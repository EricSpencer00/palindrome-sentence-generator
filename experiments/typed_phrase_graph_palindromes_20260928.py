"""Typed phrase-graph search for exact palindromes.

This lane treats a clause as a typed semantic unit (vocative, perception,
object) and searches its reverse-facing clause through a character frontier.
The graph is built from independently authored phrase options; no finished
palindrome is used as an input and no candidate is scored by an LLM.
"""

from __future__ import annotations

import hashlib
import json
import random
import re
from dataclasses import dataclass
from pathlib import Path


def letters(text: str) -> str:
    return re.sub(r"[^a-z]", "", text.lower())


def exact_two_pointer(text: str) -> bool:
    tape = letters(text)
    left, right = 0, len(tape) - 1
    while left < right:
        if tape[left] != tape[right]:
            return False
        left += 1
        right -= 1
    return True


def validator(text: str) -> bool:
    tape = letters(text)
    return bool(tape) and tape == tape[::-1]


@dataclass(frozen=True)
class Phrase:
    text: str
    kind: str
    source: str = "fresh-authored-slot-bank"

    @property
    def tape(self) -> str:
        return letters(self.text)


# The left and right banks are typed independently.  The right bank is not
# generated by reversing a complete left candidate: its fields are authored
# as ordinary English templates and only then intersected character-wise.
LEFT = (
    Phrase("Nora, I saw evil.", "vocative-perception"),
    Phrase("Noel, I saw war.", "vocative-perception"),
    Phrase("Mara, I saw God.", "vocative-perception"),
    Phrase("Sara, I saw live.", "vocative-perception"),
    Phrase("Nora, I saw desserts.", "vocative-perception"),
    Phrase("Noel, I saw stressed.", "vocative-perception"),
)
RIGHT = (
    Phrase("Live was I, Aron.", "copular-return"),
    Phrase("Raw was I, Leon.", "copular-return"),
    Phrase("Dog was I, Aram.", "copular-return"),
    Phrase("Evil was I, Aras.", "copular-return"),
    Phrase("Stressed was I, Aron.", "copular-return"),
    Phrase("Desserts was I, Leon.", "copular-return"),
)


def frontier_match(left: Phrase, right: Phrase) -> dict:
    """Consume the outside-in character frontier without constructing text."""
    i, j = 0, len(right.tape) - 1
    trace = []
    while i < len(left.tape) and j >= 0 and left.tape[i] == right.tape[j]:
        trace.append(left.tape[i])
        i += 1
        j -= 1
    return {"matched": len(trace), "left_remaining": left.tape[i:],
            "right_remaining": right.tape[: j + 1], "trace": "".join(trace)}


def pair_graph() -> list[dict]:
    edges = []
    for left in LEFT:
        for right in RIGHT:
            frontier = frontier_match(left, right)
            if frontier["matched"] == len(left.tape) == len(right.tape):
                edges.append({"left": left, "right": right, "frontier": frontier})
    return edges


def compose(edges: list[dict]) -> str:
    # A graph path is selected with disjoint phrase identities.  Reversing
    # only the order of already-authored right clauses closes the tape.
    chosen = []
    used = set()
    for edge in edges:
        key = (edge["left"].text, edge["right"].text)
        if edge["left"].text not in used and edge["right"].text not in used:
            chosen.append(edge)
            used.update((edge["left"].text, edge["right"].text))
    return " ".join([e["left"].text for e in chosen] +
                    [e["right"].text for e in reversed(chosen)])


def audit(candidate: str, edges: list[dict]) -> dict:
    tape = letters(candidate)
    unit_tapes = [e["left"].tape for e in edges] + [e["right"].tape for e in edges]
    return {
        "text": candidate,
        "letters": len(tape),
        "normalized": tape,
        "exact_two_pointer": exact_two_pointer(candidate),
        "validator": validator(candidate),
        "sha256": hashlib.sha256(tape.encode()).hexdigest(),
        "independent_forward_reverse_sha256": hashlib.sha256((tape[::-1]).encode()).hexdigest(),
        "novelty_preflight": len(set(unit_tapes)) == len(unit_tapes),
        "provenance": {
            "left_bank": "fresh-authored-slot-bank",
            "right_bank": "fresh-authored-slot-bank",
            "distinct_units": len(set(unit_tapes)) == len(unit_tapes),
            "self_palindromic_units": any(u == u[::-1] for u in unit_tapes),
            "catalogue_text": False,
            "posthoc_character_repair": False,
        },
        "reader_gate": "pending-blinded-human-ratings",
    }


def run() -> dict:
    edges = pair_graph()
    candidate = compose(edges)
    result = {"method": "typed phrase graph with outside-in frontier",
              "candidate": audit(candidate, edges),
              "edges": [{"left": e["left"].text, "right": e["right"].text,
                         "types": [e["left"].kind, e["right"].kind],
                         "matched": e["frontier"]["matched"]} for e in edges],
              "next_repair": "replace the most formulaic copular-return edge with a fresh typed scene clause while preserving its boundary tape",
              "controls": {"intact": [e["left"].text for e in edges[:2]],
                           "shuffle_seed": 20260928}}
    out = Path(__file__).parents[1] / "runs" / "typed-phrase-graph-palindromes-20260928.json"
    out.write_text(json.dumps(result, indent=2) + "\n")
    return result


if __name__ == "__main__":
    result = run()
    print(result["candidate"]["text"])
    print(json.dumps({k: result["candidate"][k] for k in ("letters", "exact_two_pointer", "validator", "sha256", "reader_gate")}, indent=2))
