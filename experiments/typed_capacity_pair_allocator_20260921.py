#!/usr/bin/env python3
"""Readable-first clause allocator: close typed pairs before capacity packing.

This is deliberately bounded.  It never stores or nests finished palindrome
chunks.  A left clause contributes a reverse-tape demand; a right clause is
eligible only when its complete character tape closes that demand.  The
capacity pass runs only over closed pairs, so it cannot turn word salad into
an apparent long result.
"""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

OUT = Path(__file__).parents[1] / "runs" / "typed-capacity-pair-allocator-20260921.json"
WORD = re.compile(r"[a-z]+")

# Fresh, ordinary clauses.  Each has a typed frame and an authored semantic
# provenance tag; no catalogue sentence or historical seed is included.
CLAUSES = [
    ("observer", "present", "the quiet archivist records a letter"),
    ("observer", "present", "the careful keeper records a message"),
    ("observer", "past", "the quiet archivist recorded a letter"),
    ("sailor", "present", "the patient sailor watches the harbor"),
    ("sailor", "past", "the patient sailor watched the harbor"),
    ("teacher", "present", "the kind teacher explains the lesson"),
    ("teacher", "past", "the kind teacher explained the lesson"),
    ("gardener", "present", "the old gardener waters the roses"),
    ("gardener", "past", "the old gardener watered the roses"),
    ("runner", "present", "a swift runner crosses the field"),
    ("runner", "past", "a swift runner crossed the field"),
    ("writer", "present", "the young writer revises a scene"),
    ("writer", "past", "the young writer revised a scene"),
]


def letters(text: str) -> str:
    return "".join(WORD.findall(text.lower()))


def audit(text: str) -> dict:
    tape = letters(text)
    rev = tape[::-1]
    h1 = hashlib.sha256(tape.encode()).hexdigest()
    h2 = hashlib.sha256(rev.encode()).hexdigest()
    mismatch = next((i for i, (a, b) in enumerate(zip(tape, rev)) if a != b), None)
    return {"letters": len(tape), "exact": tape == rev, "pointer_mismatch": mismatch,
            "forward_sha256": h1, "reverse_sha256": h2, "normalized": tape}


def independent_audit(text: str) -> dict:
    """Second implementation used for the persisted audit (not audit())."""
    tape = "".join(ch for ch in text.casefold() if "a" <= ch <= "z")
    pairs = [(tape[i], tape[-1 - i]) for i in range(len(tape) // 2)]
    return {"letters": len(tape), "exact": all(a == b for a, b in pairs),
            "first_mismatch": next((i for i, (a, b) in enumerate(pairs) if a != b), None),
            "sha256_forward": hashlib.sha256(tape.encode()).hexdigest(),
            "sha256_reverse": hashlib.sha256(tape[::-1].encode()).hexdigest()}


def main() -> None:
    rows = []
    by_tape = {}
    for role, tense, text in CLAUSES:
        tape = letters(text)
        by_tape.setdefault(tape, []).append((role, tense, text))

    # Readable-first closure: right clauses are independently selected from
    # the same authored bank, never generated by reversing a left clause.
    for l_role, l_tense, left in CLAUSES:
        demand = letters(left)[::-1]
        for r_role, r_tense, right in CLAUSES:
            rtape = letters(right)
            if rtape == demand:
                rendered = f"{left}; {right}."
                rows.append({"left": left, "right": right, "rendered": rendered,
                             "frame": [l_role, l_tense, r_role, r_tense],
                             "provenance": "fresh-authored-clause-bank",
                             "audit": audit(rendered), "independent_audit": independent_audit(rendered)})

    # Capacity packing is intentionally downstream of closure.  It therefore
    # has no ability to manufacture an exact row from unmatched controls.
    closed = [r for r in rows if r["audit"]["exact"]]
    packed = []
    if closed:
        packed = [{"rendered": " ".join(r["rendered"] for r in closed),
                   "parts": len(closed), "audit": audit(" ".join(r["rendered"] for r in closed))}]

    controls = []
    for role, tense, text in CLAUSES[:6]:
        controls.append({"rendered": text + ".", "frame": [role, tense],
                         "provenance": "fresh-authored-clause-bank", "audit": audit(text),
                         "independent_audit": independent_audit(text)})
    result = {
        "method": "typed-capacity-pair-allocator",
        "novelty_preflight": {"checked_registry": True,
            "nearest_families": ["complete-clause-reverse-intersection", "semantic-pairing-typed-clauses"],
            "status": "bounded engineering probe; capacity packing is downstream of closure and never nests chunks"},
        "bank_size": len(CLAUSES), "closure_count": len(rows), "exact_count": len(closed),
        "packed_count": len(packed), "controls": controls, "closed_pairs": rows, "packed": packed,
        "next_repair": "add independently authored lexical alternatives indexed by typed frame and first two reverse-demand characters; do not reverse or copy a completed clause",
    }
    OUT.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps({"out": str(OUT), "bank": len(CLAUSES), "closures": len(rows),
                      "exact": len(closed), "packed": len(packed),
                      "longest_control": max(c["audit"]["letters"] for c in controls)}))


if __name__ == "__main__":
    main()
