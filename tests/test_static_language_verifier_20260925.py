import importlib.util
import json
import math
from pathlib import Path
import re
import unittest

ROOT = Path(__file__).resolve().parents[1]


def load_module(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


audit = load_module(ROOT / "experiments/static_language_verifier_20260925.py", "static_audit")
deepseek = load_module(ROOT / "experiments/infer_deepseek_static_verifier_20260925.py", "static_deepseek")
table_builder = load_module(ROOT / "paper/build_static_verifier_table.py", "static_table")


class StaticLanguageVerifierTests(unittest.TestCase):
    def test_shuffle_is_deterministic_and_preserves_slots(self):
        text = "Lena, did I? I did, Ann."
        seed = audit.stable_shuffle_seed("candidate:x", 0)
        shuffled = audit.shuffle_surface(text, seed)
        self.assertEqual(shuffled, audit.shuffle_surface(text, seed))
        self.assertCountEqual(audit.words(text), audit.words(shuffled))
        self.assertEqual(re.sub(audit.WORD_RE, "<WORD>", text), re.sub(audit.WORD_RE, "<WORD>", shuffled))

    def test_pairwise_choice_maps_blind_side_to_candidate(self):
        input_data = {
            "experiment": "test",
            "items": [
                {"id": "candidate:x", "kind": "candidate", "pair_id": "x", "text": "Rain fell overnight."},
                {"id": "brown:x", "kind": "heldout_brown_prose", "pair_id": "x", "text": "Clouds drifted west."},
                {"id": "shuffle:candidate:x:00", "kind": "candidate_same_word_shuffle", "pair_id": "x", "text": "Overnight fell rain."},
            ],
        }
        specs = deepseek.comparison_specs(input_data)
        self.assertEqual(len(specs), 1)
        self.assertTrue(all(spec["candidate_side"] in {"A", "B"} for spec in specs))
        self.assertTrue(all("candidate_id" not in spec["prompt"].lower() for spec in specs))
        self.assertTrue(all("Rain fell overnight." in spec["prompt"] or "Overnight fell rain." in spec["prompt"] for spec in specs))

    def test_response_parser_rejects_out_of_protocol_choice(self):
        self.assertEqual(deepseek.parse_answer('{"choice":"A","observable_feature":"clear clause"}')['choice'], "A")
        self.assertIsNone(deepseek.parse_answer("I like B best")['choice'])

    def test_frozen_input_has_expected_rows_and_hashes(self):
        path = ROOT / "runs/static-language-verifier-20260925/input.json"
        if not path.exists():
            self.skipTest("frozen manifest is generated by the prepare step")
        data = json.loads(path.read_text())
        self.assertEqual(data["method"]["candidate_count"], 11)
        kinds = {kind: sum(item["kind"] == kind for item in data["items"]) for kind in {
            "candidate", "heldout_brown_prose", "candidate_same_word_shuffle", "brown_same_word_shuffle"
        }}
        self.assertEqual(kinds, {"candidate": 11, "heldout_brown_prose": 11, "candidate_same_word_shuffle": 352, "brown_same_word_shuffle": 352})
        for item in data["items"]:
            self.assertEqual(item["text_sha256"], audit.sha256_text(item["text"]))

    def test_completed_gpt2_output_is_full_and_untruncated(self):
        path = ROOT / "runs/static-language-verifier-20260925/gpt2.json"
        if not path.exists():
            self.skipTest("GPT-2 pass has not been retrieved from the NUC")
        result = json.loads(path.read_text())
        self.assertEqual(result["status"], "complete")
        self.assertEqual(len(result["scores"]), 726)
        self.assertRegex(result["model"]["revision"], r"^[0-9a-f]{40}$")
        for row in result["scores"]:
            self.assertEqual(row["predicted_token_count"], row["token_count"] - 1)
            self.assertTrue(math.isfinite(row["mean_token_logprob"]))
            self.assertGreater(row["predicted_token_count"], 0)

    def test_static_table_requires_all_rows_and_keeps_unit_and_limits(self):
        rows = []
        pairwise = []
        for item_id in table_builder.LABELS:
            rows.append({
                "id": item_id,
                "gpt2_candidate": {"mean_token_logprob": -2.0},
                "candidate_minus_brown_mean_token_logprob": -0.5,
                "candidate_minus_own_shuffle_mean_token_logprob": 1.0,
            })
            pairwise.append({
                "candidate_id": f"candidate:{item_id}",
                "candidate_side": "A",
                "parsed": {"choice": "A"},
            })
        report = {
            "gpt2": {"paired_rows": rows},
            "deepseek": {"comparison_summaries": {
                "candidate_same_word_shuffle": {
                    "raw_responses": pairwise,
                    "unparsed": 0,
                }
            }},
        }
        tex = table_builder.build_tex(report)
        self.assertEqual(tex.count(r"Candidate \\"), 11)
        self.assertIn("nats per token", tex)
        self.assertIn("not human readability ratings", tex)

if __name__ == "__main__":
    unittest.main()
